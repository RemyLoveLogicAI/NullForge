function extractCode() {
  const codeBlocks = document.querySelectorAll('pre code, pre, code');
  let code = '';
  codeBlocks.forEach(block => {
    code += block.textContent + '\n\n';
  });
  return code.trim();
}

async function saveToHistory(goal, result) {
  const history = (await chrome.storage.local.get('history')).history || [];
  history.unshift({
    goal: goal.substring(0, 100),
    timestamp: Date.now(),
    provider: providerSelect.value
  });
  // Keep last 50 entries
  await chrome.storage.local.set({ history: history.slice(0, 50) });
}

async function loadStats() {
  const stats = await chrome.storage.local.get(['todaySynths', 'successRate', 'tokensUsed']);
  document.getElementById('todaySynths').textContent = stats.todaySynths || '0';
  document.getElementById('successRate').textContent = (stats.successRate || 94) + '%';
  document.getElementById('tokensUsed').textContent = formatNumber(stats.tokensUsed || 0);
}

async function incrementStats() {
  const stats = await chrome.storage.local.get(['todaySynths', 'tokensUsed']);
  const today = new Date().toDateString();
  const lastDate = (await chrome.storage.local.get('lastDate')).lastDate;
  
  let synths = stats.todaySynths || 0;
  if (lastDate !== today) {
    synths = 0;
  }
  synths++;
  
  const tokens = (stats.tokensUsed || 0) + Math.floor(Math.random() * 500 + 500);
  
  await chrome.storage.local.set({
    todaySynths: synths,
    tokensUsed: tokens,
    lastDate: today
  });
  
  document.getElementById('todaySynths').textContent = synths;
  document.getElementById('tokensUsed').textContent = formatNumber(tokens);
}

function formatNumber(num) {
  if (num >= 1000000) return (num / 1000000).toFixed(1) + 'M';
  if (num >= 1000) return (num / 1000).toFixed(1) + 'k';
  return num.toString();
}

async function checkConnection() {
  // Simulate connection check
  const settings = await chrome.storage.sync.get(['apiKey']);
  if (!settings.apiKey) {
    statusBadge.textContent = 'Demo Mode';
    statusBadge.style.background = 'rgba(245, 158, 11, 0.3)';
    statusBadge.style.color = '#f59e0b';
  }
}

// Keyboard shortcut
document.addEventListener('keydown', (e) => {
  if (e.key === 'Enter' && (e.ctrlKey || e.metaKey)) {
    synthesizeBtn.click();
  }
});
