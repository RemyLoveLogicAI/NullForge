/**
 * NullForge Chrome Extension - Popup Script
 * AI-powered code synthesis from any webpage
 */

// State
let isProcessing = false;

// DOM Elements
const goalInput = document.getElementById('goalInput');
const providerSelect = document.getElementById('providerSelect');
const modelSelect = document.getElementById('modelSelect');
const synthesizeBtn = document.getElementById('synthesizeBtn');
const loading = document.getElementById('loading');
const resultPanel = document.getElementById('resultPanel');
const resultCode = document.getElementById('resultCode');
const copyBtn = document.getElementById('copyBtn');
const statusBadge = document.getElementById('statusBadge');

// Provider models mapping
const providerModels = {
  venice: ['llama-3.1-405b', 'llama-3.1-70b', 'dolphin-2.9.2-qwen2-72b'],
  openai: ['gpt-4-turbo-preview', 'gpt-4o', 'gpt-3.5-turbo'],
  anthropic: ['claude-3-5-sonnet-20241022', 'claude-3-opus-20240229'],
  ollama: ['llama3.1:70b', 'deepseek-coder-v2:latest', 'dolphin-mixtral']
};

// Initialize
document.addEventListener('DOMContentLoaded', async () => {
  // Load saved settings
  const settings = await chrome.storage.sync.get(['provider', 'model', 'apiKey']);
  if (settings.provider) {
    providerSelect.value = settings.provider;
    updateModels();
    if (settings.model) {
      modelSelect.value = settings.model;
    }
  }
  
  // Load stats
  loadStats();
  
  // Check API connection
  checkConnection();
  
  // Get selected text from active tab
  try {
    const [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
    const result = await chrome.scripting.executeScript({
      target: { tabId: tab.id },
      function: () => window.getSelection().toString()
    });
    if (result[0].result) {
      goalInput.value = `Based on this: "${result[0].result.substring(0, 500)}..."`;
    }
  } catch (e) {
    // Ignore errors from restricted pages
  }
});

// Update models when provider changes
providerSelect.addEventListener('change', () => {
  updateModels();
  saveSettings();
});

modelSelect.addEventListener('change', saveSettings);

function updateModels() {
  const provider = providerSelect.value;
  const models = providerModels[provider] || [];
  modelSelect.innerHTML = models.map(m => `<option value="${m}">${m}</option>`).join('');
}

async function saveSettings() {
  await chrome.storage.sync.set({
    provider: providerSelect.value,
    model: modelSelect.value
  });
}

// Synthesize button click
synthesizeBtn.addEventListener('click', async () => {
  const goal = goalInput.value.trim();
  if (!goal || isProcessing) return;
  
  isProcessing = true;
  synthesizeBtn.disabled = true;
  loading.classList.add('active');
  resultPanel.classList.remove('active');
  
  try {
    const result = await synthesize(goal);
    showResult(result);
    incrementStats();
  } catch (error) {
    showError(error.message);
  } finally {
    isProcessing = false;
    synthesizeBtn.disabled = false;
    loading.classList.remove('active');
  }
});

async function synthesize(goal) {
  const settings = await chrome.storage.sync.get(['apiKey', 'apiBase']);
  
  // For demo, simulate API call
  await new Promise(resolve => setTimeout(resolve, 2000));
  
  // Simulated response
  const code = `# Generated by NullForge
# Goal: ${goal.substring(0, 50)}...

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel
from typing import List, Optional

app = FastAPI(title="Generated API")

class Item(BaseModel):
    id: Optional[int] = None
    name: str
    description: Optional[str] = None

items: List[Item] = []

@app.get("/items", response_model=List[Item])
async def get_items():
    return items

@app.post("/items", response_model=Item)
async def create_item(item: Item):
    item.id = len(items) + 1
    items.append(item)
    return item

@app.get("/items/{item_id}", response_model=Item)
async def get_item(item_id: int):
    for item in items:
        if item.id == item_id:
            return item
    raise HTTPException(status_code=404, detail="Item not found")
`;
  
  return code;
}

function showResult(code) {
  resultCode.textContent = code;
  resultPanel.classList.add('active');
  
  // Save to history
  saveToHistory(goalInput.value, code);
}

function showError(message) {
  resultCode.textContent = `Error: ${message}`;
  resultPanel.classList.add('active');
  document.querySelector('.result-title').textContent = '✗ Error';
  document.querySelector('.result-title').style.color = '#ef4444';
}

// Copy to clipboard
copyBtn.addEventListener('click', async () => {
  await navigator.clipboard.writeText(resultCode.textContent);
  copyBtn.textContent = '✓';
  setTimeout(() => copyBtn.textContent = '📋', 1500);
});

// Quick actions
